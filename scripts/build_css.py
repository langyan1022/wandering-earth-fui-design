#!/usr/bin/env python3
"""Compile the skill's CSS into one stylesheet.

The reference files are the single source of truth: every rule lives in a
```css block inside references/*.md. This script concatenates those blocks, in
dependency order, into assets/fui.css so a build can link or inline one file
instead of retyping CSS out of the specs.

Usage
  python3 scripts/build_css.py                    # rewrite assets/fui.css (everything)
  python3 scripts/build_css.py --check            # exit 1 if assets/fui.css is stale
  python3 scripts/build_css.py --list             # print the module names
  python3 scripts/build_css.py --only core -o out.css
  python3 scripts/build_css.py --only core,chart,geo,devices -o out.css

`--only` takes module names (file stems, e.g. panel, chart, devices) and the
preset `core`. Tokens and foundations are always included.
No dependencies beyond the Python standard library.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REFS = ROOT / "references"
DEFAULT_OUT = ROOT / "assets" / "fui.css"

# Dependency order. Tokens and foundations first; the frame and vocabulary;
# components; then the instrument modules that build on components.
ORDER = [
    "tokens", "foundations", "i18n", "layout", "devices", "elements", "svg", "motion-spec",
    "components/panel", "components/readout", "components/gauge", "components/badge",
    "components/button", "components/form", "components/navigation", "components/table",
    "components/list", "components/chart", "components/message", "components/dialog",
    "components/states", "components/console", "components/chat", "components/media",
    "patterns", "station", "hud-viewers", "scenarios", "geo", "audio", "logos", "globe-webgl",
]
ALWAYS = ["tokens", "foundations"]
CORE = [
    "tokens", "foundations", "i18n", "layout", "elements", "motion-spec",
    "panel", "readout", "gauge", "badge", "button", "navigation", "table",
    "list", "message", "states", "patterns", "station",
]

FENCE_OPEN = re.compile(r"^```css\s*$")
FENCE_CLOSE = re.compile(r"^```\s*$")
# Blocks that are build-tool configuration, not stylesheet rules.
SKIP_MARKERS = ("@theme", '@import "tailwindcss"', "@tailwind")


def stem(module: str) -> str:
    return module.split("/")[-1]


def css_blocks(path: pathlib.Path):
    """Yield (heading, first_line_number, css_text) for each ```css block."""
    heading, inside, start, buf = "", False, 0, []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not inside:
            if line.startswith("#"):
                heading = line.lstrip("#").strip()
            elif FENCE_OPEN.match(line):
                inside, start, buf = True, number + 1, []
        elif FENCE_CLOSE.match(line):
            inside = False
            yield heading, start, "\n".join(buf).rstrip() + "\n"
        else:
            buf.append(line)


def build(selected: list[str] | None) -> tuple[str, list[str]]:
    wanted = None
    if selected is not None:
        wanted = set(ALWAYS)
        for name in selected:
            wanted.update(CORE if name == "core" else [name])
        unknown = wanted - {stem(m) for m in ORDER}
        if unknown:
            sys.exit(f"unknown module(s): {', '.join(sorted(unknown))}. Try --list.")

    parts, used = [], []
    for module in ORDER:
        if wanted is not None and stem(module) not in wanted:
            continue
        path = REFS / f"{module}.md"
        if not path.exists():
            continue
        chunk = []
        for heading, line, css in css_blocks(path):
            if any(marker in css for marker in SKIP_MARKERS):
                continue
            chunk.append(f"/* ── references/{module}.md · {heading} (line {line}) ── */\n{css}")
        if chunk:
            used.append(stem(module))
            parts.append("\n".join(chunk))

    header = (
        "/* wandering-earth-fui-design — compiled stylesheet.\n"
        " * GENERATED by scripts/build_css.py from the ```css blocks in references/*.md.\n"
        " * Do not edit this file: change the reference, then run the script again.\n"
        f" * Modules: {', '.join(used)}\n"
        " */\n\n"
    )
    return header + "\n".join(parts), used


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", help="comma-separated modules and/or the preset 'core'")
    ap.add_argument("-o", "--out", type=pathlib.Path, default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true", help="fail if the output file is out of date")
    ap.add_argument("--list", action="store_true", help="list module names and exit")
    args = ap.parse_args()

    if args.list:
        print("modules:", ", ".join(stem(m) for m in ORDER if (REFS / f"{m}.md").exists()))
        print("preset core:", ", ".join(CORE))
        return

    css, used = build(args.only.split(",") if args.only else None)

    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current != css:
            sys.exit(f"{args.out} is stale: run python3 scripts/build_css.py")
        print(f"{args.out} is up to date ({len(css):,} bytes)")
        return

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(css, encoding="utf-8", newline="\n")
    print(f"wrote {args.out} — {len(css):,} bytes, {len(used)} modules")


if __name__ == "__main__":
    main()
